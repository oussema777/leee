// Local-only real settings API/printed checkout. Ebook identity/content is a UI fixture.
import { chromium, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { createPrismaAdapter } from '../src/lib/prisma-adapter.mjs';
import { SignJWT } from 'jose';
import { randomUUID } from 'node:crypto';
const origin = process.env.AUDI_PREVIEW_ORIGIN || 'http://127.0.0.1:3120';
const url = process.env.CYBERSOURCE_TEST_DATABASE_URL;
if (!url || !['localhost','127.0.0.1'].includes(new URL(url).hostname) || new URL(url).pathname !== '/aramex_test' || !['localhost','127.0.0.1'].includes(new URL(origin).hostname)) throw Error('Local-only check');
const db = new PrismaClient({ adapter: createPrismaAdapter(url) });
const ids = ['checkout-payment-methods', 'book-restore', 'ebook-management-testing'];
const saved = await db.bookWhishSettings.findMany({ where: { id: { in: ids } } });
const id = randomUUID(), slug = 'payment-switch-' + id;
const browser = await chromium.launch();
let inventory;
try {
  const user = await db.user.create({ data: { id, email: id + '@example.test', name: 'Local switch reviewer', role: 'ADMIN', password: 'unused' } });
  await db.bookWhishSettings.deleteMany({ where: { id: 'checkout-payment-methods' } });
  const receiver = { enabled: true, accountName: 'Local receiver', accountNumber: '70123456', supportPhone: '96170123456', holdHours: 24, qrImageUrl: 'https://example.test/qr.webp', qrVerified: true };
  for (const [key,config] of [['book-restore',receiver],['ebook-management-testing',{enabled:true}]]) await db.bookWhishSettings.upsert({ where: {id:key}, create: {id:key,config,updatedBy:id}, update:{config} });
  inventory = await db.bookInventoryItem.create({ data: { sku:slug, slug, title:'Local checkout verification', author:'Test author', category:'FICTION', language:'ENGLISH', condition:'GOOD', priceCents:500, stockQuantity:1, isPublished:true, editions:{create:{label:'Local test edition',stockQuantity:1}} } });
  const token = await new SignJWT({ userId:id,email:user.email,role:user.role }).setProtectedHeader({alg:'HS256'}).setIssuedAt().setExpirationTime('15m').sign(new TextEncoder().encode(process.env.JWT_SECRET));
  const admin = await browser.newPage({viewport:{width:1200,height:900}});
  await admin.context().addCookies([{name:'admin-token',value:token,url:origin}]);
  // Production origin policy remains enabled; only this local harness supplies its expected origin.
  await admin.route('**/api/admin/payment-methods', async route => { const response = await route.fetch({headers:{...route.request().headers(),origin:'https://www.theleeexperience.com'}}); await route.fulfill({response}); });
  admin.on('response', async response => { if (response.url().endsWith('/api/admin/payment-methods') && response.request().method() === 'PUT' && !response.ok()) console.log('Settings save failed:', response.status(), await response.text()); });
  await admin.goto(origin+'/admin/payment-methods');
  const whish = admin.getByRole('switch',{name:'Whish',exact:true});
  await expect(whish).toHaveAttribute('aria-checked','false');
  await admin.screenshot({path:'.impeccable/payment-methods-off-desktop.png',fullPage:true});
  const customer = await browser.newPage({viewport:{width:1100,height:900}});
  await customer.goto(origin+'/en/books/'+slug);
  await customer.getByRole('button',{name:'Order this book',exact:true}).first().click();
  await customer.getByRole('button',{name:'Continue',exact:true}).click();
  await customer.getByRole('button',{name:/Order for myself/}).click();
  await customer.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(customer.getByRole('heading',{name:'Complete your order'})).toBeVisible();
  await expect(customer.getByText('Whish Pay',{exact:true})).toHaveCount(0);
  await expect(customer.getByRole('radio',{name:/Pay by card \(Bank Audi\)/})).toHaveCount(0);
  await whish.click(); await expect(whish).toHaveAttribute('aria-checked','true');
  await customer.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(customer.getByText('Whish Pay',{exact:true})).toBeVisible();
  await customer.getByText('Whish Pay',{exact:true}).click();
  await whish.click(); await expect(whish).toHaveAttribute('aria-checked','false');
  await customer.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(customer.getByText('Whish Pay',{exact:true})).toHaveCount(0);
  await admin.getByRole('switch',{name:'Cash',exact:true}).click();
  await expect(admin.getByRole('switch',{name:'Cash',exact:true})).toHaveAttribute('aria-checked','false');
  await customer.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(customer.getByText('Payments are temporarily paused. Please try later or contact LEE.')).toBeVisible();
  await customer.screenshot({path:'.impeccable/payment-methods-all-paused.png',fullPage:true});
  await whish.click(); await expect(whish).toHaveAttribute('aria-checked','true');
  const ebook = await browser.newPage({viewport:{width:390,height:844}});
  const fixture = { id:'switch-ebook',slug:'switch-ebook',titleEn:'Local ebook verification',titleAr:'Local ebook verification',author:'Test author',descriptionEn:'Local check',descriptionAr:'Local check',coverUrl:'',language:'ENGLISH',priceCents:500,activeVersion:{pageCount:1} };
  await ebook.route('**/api/ebooks/catalog',async route=>{const response=await route.fetch();const data=await response.json();await route.fulfill({json:{...data,ebooks:[fixture]}});});
  await ebook.route('**/api/ebooks/auth',route=>route.fulfill({json:{reader:{email:'local@example.test'}}}));
  await ebook.route('**/api/ebooks/orders',route=>route.fulfill({json:{access:[],orders:[]}}));
  await ebook.goto(origin+'/en/ebooks/switch-ebook');
  await ebook.getByRole('button',{name:'Order ebook',exact:true}).click();
  await expect(ebook.getByRole('radio',{name:/Whish/})).toBeVisible();
  await whish.click(); await expect(whish).toHaveAttribute('aria-checked','false');
  await ebook.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(ebook.getByRole('radio',{name:/Whish/})).toHaveCount(0);
  await expect(ebook.getByText('Temporary test using unvalidated payment QRs. Your order will be marked as a test.')).toHaveCount(0);
  await expect(ebook.getByRole('button',{name:'Continue to payment',exact:true})).toBeDisabled();
  await whish.click(); await expect(whish).toHaveAttribute('aria-checked','true');
  await ebook.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(ebook.getByRole('radio',{name:/Whish/})).toBeVisible();
  await admin.setViewportSize({width:390,height:844});
  expect(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await admin.screenshot({path:'.impeccable/payment-methods-mobile.png',fullPage:true});
  console.log('PASS: real admin switches; Whish hidden/restored in open printed and ebook flows; no unavailable card placeholder; all-off ordering blocked; mobile layout. No customer orders or payments created.');
} finally {
  await browser.close();
  if(inventory) await db.bookInventoryItem.delete({where:{id:inventory.id}});
  await db.bookWhishSettings.deleteMany({where:{id:{in:ids}}});
  for(const row of saved) await db.bookWhishSettings.create({data:row});
  await db.user.deleteMany({where:{id}}); await db.$disconnect();
}
